const FOLD: Record<string, string> = { Ç: "C", Ğ: "G", İ: "I", I: "I", Ö: "O", Ş: "S", Ü: "U", Â: "A", Î: "I", Û: "U" };

export function initialOf(name: string): string {
  const c = (name.trim()[0] ?? "").toLocaleUpperCase("tr");
  const f = FOLD[c] ?? c;
  return L[f] ? f : "";
}

export function letterStrokes(letter: string): P[][] {
  return L[letter] ?? [];
}
